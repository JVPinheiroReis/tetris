void piece_move_down(Piece *p) {
    p->y++;
}

void piece_move_left(Piece *p) {
    p->x--;
}

void piece_move_right(Piece *p) {
    p->x++;
}

void piece_rotate(Piece *p) {
    p->rotation++;
    if (p->rotation == 4) {
        p->rotation = 0;
    }
}

void piece_undo_rotate(Piece *p) {
    p->rotation--;
    if (p->rotation < 0) {
        p->rotation = 3;
    }
}
